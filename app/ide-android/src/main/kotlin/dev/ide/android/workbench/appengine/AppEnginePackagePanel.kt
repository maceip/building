/** A compact workbench entry, not a second app scaffold or an IDE runtime installer. */
@Composable
fun AppEnginePackagePanel(backend: IdeBackend, fileActions: FileActions, modifier: Modifier = Modifier) {
    var expanded by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf<AppEnginePackageResult?>(null) }
    Row(
        modifier.fillMaxWidth().padding(horizontal = 12.dp, vertical = 4.dp),
        horizontalArrangement = Arrangement.SpaceBetween,
    ) {
        Text("Python / Node → Android", Modifier.weight(1f).padding(vertical = 10.dp), style = MaterialTheme.typography.labelLarge)
        OutlinedButton(onClick = { expanded = true }) { Text("Package / build") }
    }
    if (expanded) AppEnginePackageDialog(backend, fileActions, generated, { generated = it }) { expanded = false }
}

@Composable
private fun AppEnginePackageDialog(
    backend: IdeBackend,
    fileActions: FileActions,
    generated: AppEnginePackageResult?,
    setGenerated: (AppEnginePackageResult?) -> Unit,
    dismiss: () -> Unit,
) {
    val context = LocalContext.current.applicationContext
    val scope = rememberCoroutineScope()
    val epoch by backend.projects.projectEpoch.collectAsState()
    val build by backend.build.buildState.collectAsState()
    val activeRoot = remember(epoch) { engineWorkspaceOrEmpty(backend) }
    var workspace by remember { mutableStateOf(activeRoot) }
    var sourceRoot by remember { mutableStateOf(".") }
    var engine by remember { mutableStateOf<AppEngine>(AppEngine.Python) }
    var entry by remember { mutableStateOf("main.py") }
    var argumentsText by remember { mutableStateOf("") }
    var payloadRoot by remember { mutableStateOf("") }
    var sourceArchive by remember { mutableStateOf("") }
    var outputParent by remember { mutableStateOf(backend.projects.projectsRootPath().orEmpty()) }
    var folder by remember { mutableStateOf("MyEngineAndroid") }
    var applicationId by remember { mutableStateOf("com.example.engineapp") }
    var label by remember { mutableStateOf("My engine app") }
    var internet by remember { mutableStateOf(false) }
    var review by remember { mutableStateOf<EnginePackageReview?>(null) }
    var busy by remember { mutableStateOf(false) }
    var notice by remember { mutableStateOf<String?>(null) }
    var reviewed by remember { mutableStateOf(false) }
    var gpl by remember { mutableStateOf(false) }
    var nodeOptIn by remember { mutableStateOf(false) }
    var payloadPage by remember { mutableStateOf(false) }
    var page by remember { mutableIntStateOf(0) }
    var debugApk by remember { mutableStateOf<Path?>(null) }
    var sourceExport by remember { mutableStateOf<Path?>(null) }
    val activeGenerated = generated != null && activeRoot == generated.projectRoot.toString()
    val idle = !busy && build.status != RunStatus.Running

    fun perform(action: suspend () -> Unit) {
        if (busy) return
        busy = true
        notice = null
        scope.launch {
            try { action() }
            catch (cancel: CancellationException) { throw cancel }
            catch (error: Exception) { notice = error.message ?: "The operation could not be completed." }
            finally { busy = false }
        }
    }

    LaunchedEffect(generated, build.status) {
        debugApk = null
        sourceExport = null
        if (generated != null) {
            val files = runInterruptible(Dispatchers.IO) { engineGeneratedArtifacts(generated) }
            debugApk = files.first
            sourceExport = files.second
        }
    }

    Dialog(onDismissRequest = { if (!busy) dismiss() }, properties = DialogProperties(usePlatformDefaultWidth = false)) {
        Surface(
            Modifier.padding(12.dp).widthIn(max = 680.dp).fillMaxWidth().fillMaxHeight(0.92f),
            shape = MaterialTheme.shapes.large,
            tonalElevation = 6.dp,
        ) {
            Column {
                Row(Modifier.fillMaxWidth().padding(12.dp), horizontalArrangement = Arrangement.SpaceBetween) {
                    Text("Embed an app engine", Modifier.weight(1f).padding(8.dp), style = MaterialTheme.typography.titleMedium)
                    TextButton(onClick = dismiss, enabled = !busy) { Text("Close") }
                }
                if (busy) LinearProgressIndicator(Modifier.fillMaxWidth())
                HorizontalDivider()
                LazyColumn(Modifier.weight(1f).padding(horizontal = 16.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
                    item {
                        Text(
                            "Create a separate native Android project embedding one selected engine and your bundled scripts. " +
                                "Local files only: nothing is downloaded, installed into the IDE, executed or built by this step. " +
                                "This is a narrow console-style runtime, not arbitrary desktop/framework compatibility.",
                            Modifier.padding(top = 12.dp), style = MaterialTheme.typography.bodySmall,
                        )
                    }
                    notice?.let { message -> item { Text(message, color = MaterialTheme.colorScheme.primary) } }
                    if (generated != null) {
                        item {
                            Text("Generated native project", style = MaterialTheme.typography.titleSmall)
                            Text(generated.projectRoot.toString(), style = MaterialTheme.typography.bodySmall)
                            Text("${generated.engine.id} · ${engineBytes(generated.bundledBytes)} runtime/app inputs (source archive additional)")
                            Text("Original source files and the active IDE project were not changed by generation.", style = MaterialTheme.typography.bodySmall)
                            Text("Corresponding source: ${generated.sourceBundle}", style = MaterialTheme.typography.bodySmall)
                        }
                        item {
                            if (!activeGenerated) {
                                Button(onClick = { perform {
                                    openEngineGeneratedProject(backend, generated)
                                    notice = "Opened the generated project. Building is a separate action."
                                } }, enabled = idle) { Text("Open generated project") }
                            } else {
                                Text("Generated project is active.")
                                Button(onClick = { perform {
                                    buildEngineGeneratedDebug(backend, generated)
                                    notice = "Started assemble:app:debug. Check the IDE build console; this is not a completed APK claim."
                                } }, enabled = idle) { Text("Build debug APK") }
                                Text("Native task: assemble:app:debug · build status: ${build.status}", style = MaterialTheme.typography.bodySmall)
                            }
                            Text("Opening explicitly switches workspaces. No Gradle wrapper or remote repository is generated.", style = MaterialTheme.typography.bodySmall)
                        }
                        item {
                            Text("Debug APK: ${generated.projectRoot.resolve("app/build/outputs/apk/debug/app-debug.apk")}", style = MaterialTheme.typography.bodySmall)
                            Text("Release signing / AAB / upload remain in the existing Play panel. Your keystore stays yours; verify actual artifact certificates there.", style = MaterialTheme.typography.bodySmall)
                            Text("An existing file does not prove this build succeeded, release signing is correct, or Play will accept it.", style = MaterialTheme.typography.bodySmall)
                            debugApk?.let { path ->
                                if (fileActions.canExport) TextButton(onClick = { perform {
                                    val checked = runInterruptible(Dispatchers.IO) { engineGeneratedArtifacts(generated).first }
                                    check(checked == path) { "Debug APK is no longer available." }
                                    fileActions.exportFile(path.toString())
                                } }, enabled = idle) { Text("Export existing debug APK") }
                            }
                            sourceExport?.let { path ->
                                if (fileActions.canExport) TextButton(onClick = { perform {
                                    val checked = runInterruptible(Dispatchers.IO) { engineGeneratedArtifacts(generated).second }
                                    check(checked == path) { "Corresponding-source archive is no longer available." }
                                    fileActions.exportFile(path.toString())
                                } }, enabled = idle) { Text("Export engine source archive") }
                            }
                            Text("The engine source archive alone is not a complete generated-app source offer; include your app/project sources and meet all distribution obligations.", style = MaterialTheme.typography.bodySmall)
                            if (fileActions.canReveal) TextButton(onClick = { fileActions.reveal(generated.projectRoot.toString()) }, enabled = idle) { Text("Show generated project in Files") }
                            TextButton(onClick = { setGenerated(null); review = null; reviewed = false; gpl = false; nodeOptIn = false }, enabled = idle) { Text("Package another app") }
                        }
                        items(generated.warnings) { limitation -> Text(limitation, style = MaterialTheme.typography.bodySmall) }
                    } else if (review == null) {
                        item {
                            Text("Application source", style = MaterialTheme.typography.titleSmall)
                            EngineField("Source workspace (absolute local path)", workspace, idle) { workspace = it }
                            if (activeRoot.isNotBlank()) TextButton(onClick = { workspace = activeRoot }, enabled = idle) { Text("Use current project") }
                            if (fileActions.canPickDirectory) TextButton(onClick = {
                                fileActions.pickDirectory { selected -> if (selected != null) workspace = selected }
                            }, enabled = idle) { Text("Choose / import source folder") }
                            Text("Without an open project, select a folder first. Android's SAF picker imports a local copy; only that copy is read.", style = MaterialTheme.typography.bodySmall)
                        }
                        item {
                            EngineField("Clean app-source subfolder (or .)", sourceRoot, idle) { sourceRoot = it }
                            Text("Select only files to embed. Hidden/build files, links and native extensions are rejected, not silently excluded. No secret scanning guarantee; do not include credentials. Limit: 10,000 files / 64 MiB.", style = MaterialTheme.typography.bodySmall)
                        }
                        item {
                            Text("Engine (one per generated APK)", style = MaterialTheme.typography.titleSmall)
                            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                                OutlinedButton(onClick = { engine = AppEngine.Python; if (entry == "main.js") entry = "main.py"; sourceArchive = "" }, enabled = idle && engine != AppEngine.Python) { Text(if (engine == AppEngine.Python) "Python selected" else "Python") }
                                OutlinedButton(onClick = { engine = AppEngine.Node; if (entry == "main.py") entry = "main.js"; sourceArchive = "" }, enabled = idle && engine != AppEngine.Node) { Text(if (engine == AppEngine.Node) "Node selected" else "Node (experimental)") }
                            }
                            EngineField("Entry inside app source (main.py / main.js)", entry, idle) { entry = it }
                            OutlinedTextField(
                                value = argumentsText, onValueChange = { argumentsText = it }, enabled = idle,
                                label = { Text("Script arguments — one literal argument per line") },
                                minLines = 2, maxLines = 5, modifier = Modifier.fillMaxWidth(),
                            )
                            Text("Empty field = no arguments. Each line is one exact argv value (including spaces); no shell parsing, quoting or engine switches. Maximum 128 arguments / 32,768 UTF-8 bytes. Standard input is available in the generated app.", style = MaterialTheme.typography.bodySmall)
                        }
                        item {
                            Text("Local engine SDK payload", style = MaterialTheme.typography.titleSmall)
                            EngineField("Payload folder (absolute local path)", payloadRoot, idle) { payloadRoot = it; sourceArchive = "" }
                            if (fileActions.canPickDirectory) TextButton(onClick = {
                                fileActions.pickDirectory { selected -> if (selected != null) { payloadRoot = selected; sourceArchive = "" } }
                            }, enabled = idle) { Text("Import matching local payload folder") }
                            Text("Choose the selected engine's pinned tools/runtime-engine/build.py output: jniLibs/, assets/, SHA256SUMS and the full corresponding-source .tar.xz. These native libraries go into the GENERATED APK, not the IDE. The optional IDE runtime pack is not this source bundle.", style = MaterialTheme.typography.bodySmall)
                            Text("Folder import/review is bounded to 512 MiB. Full source archives can be about 295 MiB and native payloads over 100 MiB; allow space for the local import plus generated project. No automatic downloads.", style = MaterialTheme.typography.bodySmall)
                        }
                        item {
                            EngineField("Exact corresponding-source .tar.xz (absolute path)", sourceArchive, idle) { sourceArchive = it }
                            TextButton(onClick = { perform {
                                sourceArchive = runInterruptible(Dispatchers.IO) {
                                    EnginePackageInputs.expectedSourceArchive(EnginePackageInputs.directory(payloadRoot, "Local payload"), engine).toString()
                                }
                                notice = "Selected the exact archive path declared by this payload. Review will verify its bytes against SHA256SUMS."
                            } }, enabled = idle && payloadRoot.isNotBlank()) { Text("Select matching archive inside payload") }
                            if (fileActions.canPickFile) TextButton(onClick = {
                                fileActions.pickFile(listOf("xz")) { selected -> if (selected != null) sourceArchive = selected }
                            }, enabled = idle) { Text("Choose corresponding-source file") }
                            Text("The complete matching archive must also exist inside the payload folder. A picked SAF copy is accepted only after its full SHA-256 matches that archive; no substitute or partial source bundle is accepted.", style = MaterialTheme.typography.bodySmall)
                        }
                        item { EngineField("Output parent (existing local directory)", outputParent, idle) { outputParent = it } }
                        item { EngineField("New project folder name", folder, idle) { folder = it } }
                        item { EngineField("Android application ID", applicationId, idle) { applicationId = it } }
                        item { EngineField("App label", label, idle) { label = it } }
                        item {
                            EngineToggle("Include Android INTERNET permission (off by default; does not add CA roots or framework support)", internet, idle) { internet = it }
                            Button(onClick = { perform {
                                review = runInterruptible(Dispatchers.IO) {
                                    val source = EnginePackageInputs.sourceDirectory(workspace, sourceRoot)
                                    val destination = EnginePackageInputs.destination(outputParent, folder)
                                    val payload = EnginePackageInputs.directory(payloadRoot, "Local payload")
                                    val request = AppEnginePackageRequest(
                                        sourceRoot = source,
                                        entry = entry,
                                        destination = destination,
                                        applicationId = applicationId,
                                        label = label,
                                        engine = engine,
                                        payloadRoot = payload,
                                        runtimeClassesJar = installedEngineSdk(context),
                                        internetPermission = internet,
                                        arguments = EnginePackageInputs.arguments(argumentsText),
                                    )
                                    EnginePackageInputs.review(request, sourceArchive)
                                }
                                reviewed = false; gpl = false; nodeOptIn = false; page = 0; payloadPage = false
                            } }, enabled = idle) { Text("Hash inputs and review") }
                            Text("Large payloads are hashed as streams off the UI thread. Review neither edits source files nor creates the destination.", style = MaterialTheme.typography.bodySmall)
                        }
                    } else {
                        val snapshot = review!!
                        item {
                            Text("Review before creating", style = MaterialTheme.typography.titleSmall)
                            Text("${snapshot.request.engine.id} ${snapshot.version} · ${snapshot.abi} · minimum Android API ${snapshot.minimumApi}")
                            Text("Payload support: ${snapshot.support} · qualified: ${snapshot.qualification}", style = MaterialTheme.typography.bodySmall)
                            Text("${snapshot.request.label} · ${snapshot.request.applicationId}")
                            Text("Entry: ${snapshot.request.entry} · ${snapshot.request.arguments.size} arguments · INTERNET: ${snapshot.request.internetPermission}", style = MaterialTheme.typography.bodySmall)
                            if (snapshot.request.arguments.isNotEmpty()) Text(snapshot.request.arguments.mapIndexed { index, argument -> "argv[$index] = ${argument.ifEmpty { "<empty>" }}" }.joinToString("\n"), style = MaterialTheme.typography.bodySmall)
                            Text("Source: ${snapshot.request.sourceRoot}\nOutput: ${snapshot.request.destination}\nPayload: ${snapshot.request.payloadRoot}", style = MaterialTheme.typography.bodySmall)
                            Text("${snapshot.sourceInputs.size} app files / ${engineBytes(snapshot.sourceBytes)}\n${snapshot.payloadInputs.size} payload files / ${engineBytes(snapshot.payloadBytes)}", style = MaterialTheme.typography.bodySmall)
                            Text("App input-list SHA-256: ${snapshot.sourceIdentity}\nPayload input-list SHA-256: ${snapshot.payloadIdentity}\nBundled runtime SDK SHA-256: ${snapshot.runtimeIdentity}", style = MaterialTheme.typography.bodySmall)
                        }
                        items(AppEngineCapabilities.limitations(snapshot.request.engine)) { limitation -> Text(limitation, style = MaterialTheme.typography.bodySmall) }
                        item {
                            Text("Licensing / source identity", style = MaterialTheme.typography.titleSmall)
                            Text("Runtime GPL-3.0-or-later; no runtime linking exception. Payload declares ${snapshot.license}.", style = MaterialTheme.typography.bodySmall)
                            Text("${snapshot.correspondingSource.path}\nSelected: ${snapshot.selectedSourceArchive}\n${engineBytes(snapshot.correspondingSource.bytes)}\nSHA-256 ${snapshot.correspondingSource.sha256}", style = MaterialTheme.typography.bodySmall)
                            Text(snapshot.notice, style = MaterialTheme.typography.bodySmall)
                            Text("Actual engine notices are under assets/runtime-engine/${snapshot.request.engine.id}/licenses. Hash matching proves file identity, not trust, legal compliance or device qualification.", style = MaterialTheme.typography.bodySmall)
                        }
                        item {
                            TextButton(onClick = { payloadPage = !payloadPage; page = 0 }, enabled = !busy) { Text(if (payloadPage) "Review app inputs" else "Review payload / license files") }
                        }
                        val inputs = if (payloadPage) snapshot.payloadInputs else snapshot.sourceInputs
                        val start = (page * ENGINE_PAGE_SIZE).coerceAtMost(inputs.size)
                        items(inputs.drop(start).take(ENGINE_PAGE_SIZE), key = { "${if (payloadPage) "payload" else "source"}:${it.path}" }) { input ->
                            Text("${input.path} · ${engineBytes(input.bytes)}\nSHA-256 ${input.sha256}", style = MaterialTheme.typography.bodySmall)
                        }
                        item {
                            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                                TextButton(onClick = { page-- }, enabled = !busy && page > 0) { Text("Previous") }
                                Text("${if (inputs.isEmpty()) 0 else start + 1}–${(start + ENGINE_PAGE_SIZE).coerceAtMost(inputs.size)} / ${inputs.size}", Modifier.padding(top = 12.dp))
                                TextButton(onClick = { page++ }, enabled = !busy && start + ENGINE_PAGE_SIZE < inputs.size) { Text("Next") }
                            }
                        }
                        item {
                            EngineToggle("I reviewed the exact input hashes, app identity and separate new destination. No existing output may be overwritten; source files must stay unchanged.", reviewed, idle) { reviewed = it }
                            EngineToggle("I acknowledge GPL-3.0-or-later distribution/source obligations, no runtime linking exception, and the need to review all bundled package licenses. Creating a project is not legal approval.", gpl, idle) { gpl = it }
                            if (snapshot.request.engine == AppEngine.Node) EngineToggle("I explicitly opt in to unqualified experimental Node on Android for my own device/app qualification. Upstream does not support this platform.", nodeOptIn, idle) { nodeOptIn = it }
                            Button(onClick = { perform {
                                val result = runInterruptible(Dispatchers.IO) { EnginePackageInputs.create(snapshot, gpl, nodeOptIn) }
                                setGenerated(result)
                                review = null
                                notice = "Created the separate native Android project using AppEnginePackager. Open and build it explicitly below."
                            } }, enabled = idle && reviewed && gpl && (snapshot.request.engine != AppEngine.Node || nodeOptIn)) { Text("Confirm and create Android project") }
                            TextButton(onClick = { review = null; reviewed = false; gpl = false; nodeOptIn = false }, enabled = !busy) { Text("Back to inputs") }
                        }
                    }
                    item { Text("Packaging is not signing, installing, uploading or a claim that every Node/Python package works on Android.", Modifier.padding(bottom = 16.dp), style = MaterialTheme.typography.bodySmall) }
                }
            }
        }
    }
}

@Composable
private fun EngineField(label: String, value: String, enabled: Boolean, change: (String) -> Unit) {
    OutlinedTextField(value = value, onValueChange = change, label = { Text(label) }, enabled = enabled, singleLine = true, modifier = Modifier.fillMaxWidth())
}

@Composable
private fun EngineToggle(label: String, checked: Boolean, enabled: Boolean, change: (Boolean) -> Unit) {
    Row {
        Checkbox(checked = checked, onCheckedChange = change, enabled = enabled)
        Text(label, Modifier.weight(1f).padding(top = 12.dp), style = MaterialTheme.typography.bodySmall)
    }
}

@Suppress("DEPRECATION")
private fun installedEngineSdk(context: Context): Path {
    val info = context.packageManager.getPackageInfo(context.packageName, 0)
    val apk = File(context.applicationInfo.sourceDir)
    val stamp = "${info.versionCode}-${info.lastUpdateTime}-${apk.length()}-${apk.lastModified()}"
    return EngineSdkCache.extract(context.cacheDir.canonicalFile.toPath(), stamp) {
        try { context.assets.open(EngineSdkCache.ASSET_NAME) }
        catch (error: java.io.IOException) {
            throw java.io.IOException("This IDE APK has no readable ${EngineSdkCache.ASSET_NAME}. Install a build that includes the real Java-8 runtime SDK asset; a CLI runtime pack is not a substitute.", error)
        }
    }
}

private fun engineBytes(bytes: Long): String = when {
    bytes >= 1024 * 1024 -> "${bytes / (1024 * 1024)} MiB"
    bytes >= 1024 -> "${bytes / 1024} KiB"
    else -> "$bytes B"
}

private const val ENGINE_PAGE_SIZE = 30
